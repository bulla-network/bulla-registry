// Builds dist/ for the @bulla/registry npm package: registry.json as an ES module and a CommonJS module, with
// TypeScript types generated from registry.schema.json, and each ABI as its bare abi array. registry.json and the
// schema ship as they are, next to dist/; package.json's "files" lists them.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";
import { compile } from "json-schema-to-typescript";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type JsonObject = { [key: string]: Json };

const ADDRESS_REF = "#/definitions/address";

const isObject = (v: unknown): v is JsonObject => typeof v === "object" && v !== null && !Array.isArray(v);

/**
 * A copy of the schema with tsType hints, which json-schema-to-typescript reads and Ajv (strict) would reject, so
 * they are added here rather than in registry.schema.json:
 * - addresses are `0x${string}`, viem's Address, so consumers can pass them to viem without a cast
 * - contracts is keyed by the source repos its propertyNames lists, rather than by any string
 */
export function withTypeHints(schema: JsonObject): JsonObject {
  const copy = structuredClone(schema);

  const walk = (node: Json): void => {
    if (Array.isArray(node)) return node.forEach(walk);
    if (!isObject(node)) return;
    // A $ref with a sibling description generates a plain string, so name the type outright.
    if (node.$ref === ADDRESS_REF) node.tsType = "Address";
    Object.values(node).forEach(walk);
  };
  walk(copy);

  const definitions = copy.definitions as JsonObject;
  (definitions.address as JsonObject).tsType = "`0x${string}`";

  const network = definitions.network as JsonObject;
  const contracts = (network.properties as JsonObject).contracts as JsonObject;
  const repos = (contracts.propertyNames as JsonObject).enum as string[];
  contracts.tsType = `Partial<Record<${repos.map((r) => JSON.stringify(r)).join(" | ")}, Record<string, Address>>>`;

  return copy;
}

/** The TypeScript declarations for registry.schema.json: BullaRegistry and the types it is made of. */
export async function generateTypes(schema: JsonObject): Promise<string> {
  const types = await compile(withTypeHints(schema) as Parameters<typeof compile>[0], "BullaRegistry", {
    bannerComment: "",
    additionalProperties: false,
    format: true,
  });
  // The tsType hints name Address in place of every $ref to it, so compile may not declare it.
  if (/export type Address = /.test(types)) return types;
  return `/**\n * An EVM address, as viem's Address.\n */\nexport type Address = \`0x\${string}\`;\n${types}`;
}

/**
 * Writes each <repo>/abis/<Name>.json as dist/abis/<repo>/<Name>.json, keeping only the abi array. The V1 and V2
 * exports are full compiler artifacts: their bytecode and metadata are compiled BUSL-1.1 code, which the package's
 * MIT license must not cover, and consumers only need the ABI.
 */
export function writeAbis(root: string, out: string): string[] {
  const written: string[] = [];
  for (const repo of readdirSync(root)) {
    const dir = join(root, repo, "abis");
    if (repo === "node_modules" || repo.startsWith(".") || !statSync(join(root, repo)).isDirectory() || !existsSync(dir)) continue;
    for (const name of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
      const artifact = JSON.parse(readFileSync(join(dir, name), "utf-8"));
      const abi = Array.isArray(artifact) ? artifact : artifact.abi;
      if (!Array.isArray(abi)) throw new Error(`${repo}/abis/${name} has no abi array`);
      mkdirSync(join(out, "abis", repo), { recursive: true });
      writeFileSync(join(out, "abis", repo, name), JSON.stringify(abi, null, 2) + "\n");
      written.push(`${repo}/${name}`);
    }
  }
  return written;
}

export async function buildPackage(root: string = ROOT, out: string = join(root, "dist")): Promise<void> {
  const registry = JSON.parse(readFileSync(join(root, "registry.json"), "utf-8"));
  const schema = JSON.parse(readFileSync(join(root, "registry.schema.json"), "utf-8"));
  const types = await generateTypes(schema);

  const header = "// Generated by scripts/build-package.ts from registry.json and registry.schema.json. Do not edit.\n";
  const data = JSON.stringify(registry, null, 2);

  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });

  writeFileSync(join(out, "index.js"), `${header}export const registry = ${data};\nexport default registry;\n`);
  writeFileSync(
    join(out, "index.cjs"),
    `${header}"use strict";\nObject.defineProperty(exports, "__esModule", { value: true });\n` +
      `const registry = ${data};\nexports.registry = registry;\nexports.default = registry;\n`,
  );

  const declarations = `${header}${types}\nexport declare const registry: BullaRegistry;\nexport default registry;\n`;
  writeFileSync(join(out, "index.d.ts"), declarations);
  writeFileSync(join(out, "index.d.cts"), declarations);

  writeAbis(root, out);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await buildPackage();
  console.log("Built dist/ (index.js, index.cjs, index.d.ts, index.d.cts, abis/)");
}
